interface MinutesI18nValue {
  locale: MinutesLocale;
  t: (key: MinutesTextKey, vars?: Record<string, string | number>) => string;
}

const MinutesI18nContext = createContext<MinutesI18nValue>({
  locale: "en",
  t: (key, vars) => interpolate(EN_TEXT[key], vars),
});

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, k: string) =>
    Object.hasOwn(vars, k) ? String(vars[k]) : `{${k}}`,
  );
}

export function MinutesLocaleProvider({
  locale,
  children,
}: {
  locale: MinutesLocale;
  children: ReactNode;
}) {
  const value = useMemo<MinutesI18nValue>(() => {
    const table = locale === "zh-HK" ? ZH_HK_TEXT : EN_TEXT;
    return {
      locale,
      t: (key, vars) => interpolate(table[key], vars),
    };
  }, [locale]);

  const sharedTranslator = useMemo(() => {
    if (locale !== "zh-HK") return null;
    return (english: string) => SHARED_UI_ZH_HK[english] ?? english;
  }, [locale]);

  return (
    <LocaleTextProvider value={sharedTranslator}>
      <MinutesI18nContext.Provider value={value}>{children}</MinutesI18nContext.Provider>
    </LocaleTextProvider>
  );
}

export function useMinutesText(): MinutesI18nValue {
  return useContext(MinutesI18nContext);
}
